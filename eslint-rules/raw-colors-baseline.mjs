/**
 * Legacy raw-palette baseline for the `no-raw-colors` ESLint rule.
 *
 * Generated, not hand-maintained. Regenerate with:
 *
 *     npm run lint:baseline
 *
 * Verify without writing:
 *
 *     node scripts/update-raw-colors-baseline.mjs --check
 *
 * ## Why this exists
 *
 * `no-raw-colors` (added in 3d66d0e0c) is correct about what it reports: the
 * rule's own test suite passes. But it flags ~1,800 pre-existing usages, and CI
 * gates on `--max-warnings 0`, so enabling it repo-wide fails every push.
 *
 * ## Why a baseline rather than turning the rule off
 *
 * Turning the rule off entirely would also stop it catching NEW raw colours,
 * which is the actual value. This list scopes the waiver to files that already
 * carry the debt, so the rule stays live everywhere else - including any file
 * added after this baseline was generated.
 *
 * ## Why a blanket autofix is not the answer
 *
 * Only ~31 reports are autofixable, and several would change rendering rather
 * than spelling. Roughly 486 are state variants (`hover:`, `disabled:`,
 * `group-hover:`, `dark:hover:`) that the rule describes as lacking a
 * "dark-mode counterpart" - but a hover state is not a theme. Rewriting
 * `hover:text-slate-700` to `hover:text-muted` would collapse a deliberate
 * hover step onto the resting colour. `bg-white ... dark:bg-transparent` on
 * the chrome surfaces is another: `bg-surface-100` is not a synonym for
 * `transparent`. The sweep needs per-group visual review.
 *
 * ## Scope: why this is a union of two scans
 *
 * The two scans see different code, and the baseline must cover both:
 *
 *   - The committed tree, which is what CI lints. Authoritative.
 *   - The working tree, which can carry an in-progress token sweep that has
 *     already cleaned files that are not committed yet.
 *
 * Regenerating from the working tree alone drops files CI still flags, and the
 * push fails. Regenerating from the committed tree alone stops the waiver from
 * tracking local progress. A file therefore stays listed until it is clean in
 * BOTH. Extra entries only suppress a warning that is not firing, so they are
 * harmless, and `npm run lint:baseline` prunes them once the sweep lands.
 */
