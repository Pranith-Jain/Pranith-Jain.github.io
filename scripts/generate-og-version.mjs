#!/usr/bin/env node
/**
 * Regenerate worker/og-version.generated.ts with a fresh build version.
 *
 * Runs in the prebuild chain (before vite build) so every deployment emits
 * NEW og:image / twitter:image URLs (`/og-image/v<ver>/page/<id>.png`).
 *
 * WHY: X/Twitter caches card state per URL — including image-fetch failures
 * from past deploy windows — for days. A per-deploy version segment makes X
 * treat each deploy's image URLs as brand-new resources and re-crawl them,
 * instead of serving the poisoned image-less fallback forever.
 *
 * Run: node scripts/generate-og-version.mjs
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';
import { execSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'worker', 'og-version.generated.ts');

// Version = git short SHA: unique per code state, so every deploy that
// changes anything gets fresh OG URLs, while repeated deploys of the same
// commit stay stable.
let stamp = '';
try {
  stamp = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
} catch {
  stamp = new Date().toISOString().slice(0, 10).replace(/-/g, ''); // fallback outside git
}
const content = `/**
 * BUILD-GENERATED — do not edit by hand. Regenerated by scripts/generate-og-version.mjs.
 *
 * Baked into every dynamic OG-card URL (\`/og-image/v<ver>/page/<id>.png\`) so
 * each deploy emits brand-new og:image / twitter:image URLs. X/Twitter caches
 * card metadata (including image-fetch failures) per URL for days; a per-deploy
 * version segment forces a clean re-crawl of every card after each deploy.
 */
export const OG_BUILD_VERSION = 'v${stamp}';
`;
writeFileSync(OUT, content);
console.log(`  og-version -> ${stamp}`);
